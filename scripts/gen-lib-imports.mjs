// Generates src/typecheck/lib-imports.ts: the complete lib.es2022.d.ts
// reference closure from node_modules/typescript/lib as wrangler Text-rule
// imports (default export = file text). Run once and commit; regenerate only
// when the typescript pin changes — the boot assert in src/typecheck/index.ts
// catches drift.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const libDir = join(root, "node_modules", "typescript", "lib");
const outFile = join(root, "src", "typecheck", "lib-imports.ts");
const HEAD = "lib.es2022.d.ts";

function refsOf(fileName) {
  const text = readFileSync(join(libDir, fileName), "utf8");
  return [...text.matchAll(/^\/\/\/\s*<reference\s+lib="([^"]+)"\s*\/>\s*$/gm)].map(
    (m) => `lib.${m[1]}.d.ts`,
  );
}

const closure = new Set([HEAD]);
for (const queue = [HEAD]; queue.length > 0; ) {
  const f = queue.shift();
  for (const ref of refsOf(f)) {
    if (!closure.has(ref)) {
      closure.add(ref);
      queue.push(ref);
    }
  }
}
const files = [...closure].sort();

function ident(fileName) {
  return (
    "lib" +
    fileName
      .replace(/^lib\./, "")
      .replace(/\.d\.ts$/, "")
      .split(".")
      .map((s) => s[0].toUpperCase() + s.slice(1))
      .join("")
  );
}

const lines = [
  "// @ts-nocheck — .d.ts files are imported as wrangler Text modules (strings);",
  "// host tsc rejects declaration-file imports (TS2306/TS2846) and an ambient",
  "// wildcard shim is shadowed by real-file resolution, so this generated file",
  "// opts out of checking. The Record<string, string> annotation below keeps",
  "// consumers typed.",
  "// Generated by scripts/gen-lib-imports.mjs — do not edit by hand.",
  `// ${files.length} files = the lib.es2022.d.ts reference closure (no DOM).`,
];
for (const f of files) {
  lines.push(`import ${ident(f)} from "typescript/lib/${f}";`);
}
lines.push("");
lines.push("export const LIB_FILES: Record<string, string> = {");
for (const f of files) {
  lines.push(`  "${f}": ${ident(f)},`);
}
lines.push("};");
lines.push("");
writeFileSync(outFile, lines.join("\n"));
console.log(`wrote ${outFile}: ${files.length} imports`);
